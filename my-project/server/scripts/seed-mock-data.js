#!/usr/bin/env node
// Seeds the mock admins, security staff, students, 15 found items and sample claims.
//
//   node scripts/seed-mock-data.js           insert / update the mock data (safe to run many times)
//   node scripts/seed-mock-data.js --reset   remove ONLY the mock rows (fixed IDs / mock emails)
//   node scripts/seed-mock-data.js --sql     write mock-data/seed_mock_data.sql (for the Supabase SQL editor)
//
// Data lives in mock-data/*.json so it is easy to read and edit.
// Passwords in users.json are plain text for demos; only bcrypt hashes reach the database.

const path = require('path');
const fs = require('fs');
const dotenv = require('dotenv');
const bcrypt = require('bcryptjs');

const ROOT = path.resolve(__dirname, '..');
for (const p of [path.join(ROOT, '.env'), path.resolve(ROOT, '../../Lost_Found_System-main/.env'), path.resolve(ROOT, '../../.env')]) {
  if (fs.existsSync(p)) dotenv.config({ path: p, quiet: true });
}

const load = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'mock-data', f), 'utf8'));
const { users } = load('users.json');
const { items } = load('found-items.json');
const { inquiries } = load('inquiries.json');

const CATEGORIES = ['electronics', 'personal-items', 'documents', 'clothing', 'keys', 'other'];
const STATUSES = ['unclaimed', 'claimed', 'pending-verification'];

function validate() {
  const emails = new Set(users.map((u) => u.email));
  for (const i of items) {
    if (!CATEGORIES.includes(i.category)) throw new Error(`${i.title}: bad category ${i.category}`);
    if (!STATUSES.includes(i.status)) throw new Error(`${i.title}: bad status ${i.status}`);
    if (!emails.has(i.postedBy)) throw new Error(`${i.title}: postedBy ${i.postedBy} is not a mock user`);
    const poster = users.find((u) => u.email === i.postedBy);
    if (poster.role === 'student') throw new Error(`${i.title}: only staff can post items`);
  }
  for (const q of inquiries) {
    if (!items.some((i) => i.id === q.itemId)) throw new Error(`inquiry ${q.id}: unknown item`);
    if (!emails.has(q.claimant)) throw new Error(`inquiry ${q.id}: unknown claimant`);
  }
}

const sqlStr = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

async function hashed() {
  return Promise.all(users.map(async (u) => ({ ...u, hash: await bcrypt.hash(u.password, 10) })));
}

async function writeSql() {
  const hu = await hashed();
  const out = [];
  out.push('-- Generated by: node scripts/seed-mock-data.js --sql');
  out.push('-- Paste into the Supabase SQL editor (or: psql "$DATABASE_URL" -f mock-data/seed_mock_data.sql).');
  out.push('-- Safe to run more than once. Logins are listed in mock-data/MOCK_CREDENTIALS.md.');
  out.push('BEGIN;');
  out.push('');
  out.push('-- 1. Users: 2 admins, 5 security staff, 3 students');
  for (const u of hu) {
    out.push(`INSERT INTO users (id, full_name, email, hashed_password, role, student_id) VALUES (${sqlStr(u.id)}, ${sqlStr(u.fullName)}, ${sqlStr(u.email)}, ${sqlStr(u.hash)}, ${sqlStr(u.role)}, ${sqlStr(u.schoolId)})
  ON CONFLICT (email) DO UPDATE SET full_name = EXCLUDED.full_name, hashed_password = EXCLUDED.hashed_password, role = EXCLUDED.role, student_id = EXCLUDED.student_id;`);
  }
  out.push('');
  out.push('-- 2. Found items (posted_by is looked up by email so it works even if a user already existed)');
  for (const i of items) {
    out.push(`INSERT INTO found_items (id, posted_by_user_id, title, description, category, location_found, date_found, status)
  SELECT ${sqlStr(i.id)}, u.id, ${sqlStr(i.title)}, ${sqlStr(i.description)}, ${sqlStr(i.category)}, ${sqlStr(i.location)}, ${sqlStr(i.dateFound)}, ${sqlStr(i.status)} FROM users u WHERE u.email = ${sqlStr(i.postedBy)}
  ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description, category = EXCLUDED.category, location_found = EXCLUDED.location_found, date_found = EXCLUDED.date_found, status = EXCLUDED.status, updated_at = now();`);
  }
  out.push('');
  out.push('-- 3. Claims (inquiries) and their messages');
  for (const q of inquiries) {
    out.push(`INSERT INTO inquiries (id, found_item_id, claimant_user_id, status, claim_description)
  SELECT ${sqlStr(q.id)}, ${sqlStr(q.itemId)}, u.id, ${sqlStr(q.status)}, ${sqlStr(q.claimDescription)} FROM users u WHERE u.email = ${sqlStr(q.claimant)}
  ON CONFLICT (id) DO UPDATE SET status = EXCLUDED.status, claim_description = EXCLUDED.claim_description, updated_at = now();`);
    out.push(`DELETE FROM inquiry_messages WHERE inquiry_id = ${sqlStr(q.id)};`);
    q.messages.forEach((m, n) => {
      out.push(`INSERT INTO inquiry_messages (inquiry_id, sender_user_id, message, sent_at)
  SELECT ${sqlStr(q.id)}, u.id, ${sqlStr(m.text)}, now() - interval '${(q.messages.length - n) * 10} minutes' FROM users u WHERE u.email = ${sqlStr(m.from)};`);
    });
  }
  out.push('');
  out.push('COMMIT;');
  const file = path.join(ROOT, 'mock-data', 'seed_mock_data.sql');
  fs.writeFileSync(file, `${out.join('\n')}\n`);
  console.log(`Wrote ${path.relative(process.cwd(), file)}`);
}

async function seed(db) {
  const hu = await hashed();
  const client = await db.connect();
  try {
    await client.query('BEGIN');
    const idByEmail = {};
    for (const u of hu) {
      const { rows } = await client.query(
        `INSERT INTO users (id, full_name, email, hashed_password, role, student_id)
         VALUES ($1, $2, $3, $4, $5, $6)
         ON CONFLICT (email) DO UPDATE SET full_name = EXCLUDED.full_name, hashed_password = EXCLUDED.hashed_password,
           role = EXCLUDED.role, student_id = EXCLUDED.student_id
         RETURNING id`,
        [u.id, u.fullName, u.email, u.hash, u.role, u.schoolId]);
      idByEmail[u.email] = rows[0].id;
    }
    for (const i of items) {
      await client.query(
        `INSERT INTO found_items (id, posted_by_user_id, title, description, category, location_found, date_found, status)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
         ON CONFLICT (id) DO UPDATE SET posted_by_user_id = EXCLUDED.posted_by_user_id, title = EXCLUDED.title,
           description = EXCLUDED.description, category = EXCLUDED.category, location_found = EXCLUDED.location_found,
           date_found = EXCLUDED.date_found, status = EXCLUDED.status, updated_at = now()`,
        [i.id, idByEmail[i.postedBy], i.title, i.description, i.category, i.location, i.dateFound, i.status]);
    }
    for (const q of inquiries) {
      await client.query(
        `INSERT INTO inquiries (id, found_item_id, claimant_user_id, status, claim_description)
         VALUES ($1, $2, $3, $4, $5)
         ON CONFLICT (id) DO UPDATE SET status = EXCLUDED.status, claim_description = EXCLUDED.claim_description, updated_at = now()`,
        [q.id, q.itemId, idByEmail[q.claimant], q.status, q.claimDescription]);
      await client.query('DELETE FROM inquiry_messages WHERE inquiry_id = $1', [q.id]);
      for (const [n, m] of q.messages.entries()) {
        await client.query(
          `INSERT INTO inquiry_messages (inquiry_id, sender_user_id, message, sent_at)
           VALUES ($1, $2, $3, now() - ($4 || ' minutes')::interval)`,
          [q.id, idByEmail[m.from], m.text, String((q.messages.length - n) * 10)]);
      }
    }
    await client.query('COMMIT');
  } catch (e) {
    await client.query('ROLLBACK').catch(() => {});
    throw e;
  } finally {
    client.release();
  }

  const counts = await db.query(`SELECT
      (SELECT count(*) FROM users WHERE role = 'admin')    AS admins,
      (SELECT count(*) FROM users WHERE role = 'security') AS security,
      (SELECT count(*) FROM users WHERE role = 'student')  AS students,
      (SELECT count(*) FROM found_items)                   AS items,
      (SELECT count(*) FROM inquiries)                     AS claims`);
  console.log('Mock data seeded.');
  console.table(users.map((u) => ({ role: u.role, name: u.fullName, email: u.email, password: u.password, schoolId: u.schoolId })));
  console.log(`Items seeded: ${items.length}. Claims seeded: ${inquiries.length}.`);
  console.log('Totals now in the database:', counts.rows[0]);
}

async function reset(db) {
  const itemIds = items.map((i) => i.id);
  const emails = users.map((u) => u.email);
  const client = await db.connect();
  try {
    await client.query('BEGIN');
    await client.query('DELETE FROM inquiry_messages WHERE inquiry_id IN (SELECT id FROM inquiries WHERE found_item_id = ANY($1::uuid[]))', [itemIds]);
    await client.query('DELETE FROM inquiries WHERE found_item_id = ANY($1::uuid[])', [itemIds]);
    await client.query('DELETE FROM flagged_checks WHERE found_item_id = ANY($1::uuid[])', [itemIds]);
    await client.query('DELETE FROM found_items WHERE id = ANY($1::uuid[])', [itemIds]);
    // Only delete mock users that no longer own real data.
    const r = await client.query(
      `DELETE FROM users u WHERE u.email = ANY($1::varchar[])
         AND NOT EXISTS (SELECT 1 FROM found_items f WHERE f.posted_by_user_id = u.id)
         AND NOT EXISTS (SELECT 1 FROM inquiries i WHERE i.claimant_user_id = u.id)
         AND NOT EXISTS (SELECT 1 FROM inquiry_messages m WHERE m.sender_user_id = u.id)`, [emails]);
    await client.query('COMMIT');
    console.log(`Removed ${itemIds.length} mock items and ${r.rowCount} mock users.`);
  } catch (e) {
    await client.query('ROLLBACK').catch(() => {});
    throw e;
  } finally {
    client.release();
  }
}

(async () => {
  validate();
  const args = process.argv.slice(2);
  if (args.includes('--sql')) return writeSql();
  if (!process.env.DATABASE_URL) {
    console.error('DATABASE_URL is not set. Add it to my-project/server/.env first.');
    process.exit(1);
  }
  const db = require('../db');
  try {
    if (args.includes('--reset')) await reset(db);
    else await seed(db);
  } catch (e) {
    console.error('Seeding failed:', e.message);
    if (e.code === '42P01') console.error('A table is missing. Run schema.sql first.');
    process.exitCode = 1;
  } finally {
    await db.end();
  }
  return undefined;
})();
